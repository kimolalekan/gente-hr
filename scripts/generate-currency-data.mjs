/**
 * One-off generator for the currency + flag data used by the company
 * settings form (all countries' currencies with SVG flags).
 *
 * Inputs:
 *   1. <countriesJson>  — mledoze/countries `countries.json`
 *      (https://raw.githubusercontent.com/mledoze/countries/master/countries.json)
 *   2. <flagsDir>       — extracted `string/3x2` directory from the
 *      `country-flag-icons` npm package tarball
 *
 * Outputs:
 *   - src/lib/currency-data.ts  — every currency used by any country, with a
 *     representative SVG flag code and the list of countries that use it
 *   - public/flags/<CODE>.svg   — the SVG flags themselves, served as static
 *     assets so they never bloat the JS bundle
 *
 * Usage: node scripts/generate-currency-data.mjs <countries.json> <flagsDir>
 */
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [, , countriesPath, flagsDir] = process.argv;
if (!countriesPath || !flagsDir) {
  console.error(
    "Usage: node scripts/generate-currency-data.mjs <countries.json> <flagsDir>",
  );
  process.exit(1);
}

/** Flags that represent a currency better than the first country alphabetically. */
const FLAG_OVERRIDES = {
  EUR: "EU", // European Union
  USD: "US", // American Samoa sorts before the US in the country list
  GBP: "GB", // Guernsey sorts before the UK
  CHF: "CH", // Liechtenstein sorts before Switzerland
};

const countries = JSON.parse(readFileSync(countriesPath, "utf8"));

// flag code → svg string, from the extracted country-flag-icons `string/3x2` dir
const availableFlags = new Set(
  readdirSync(flagsDir).map((f) => f.replace(/\.js$/, "")),
);
const svgCache = new Map();
function getSvg(code) {
  if (!svgCache.has(code)) {
    try {
      const raw = readFileSync(join(flagsDir, `${code}.js`), "utf8");
      svgCache.set(code, raw.match(/<svg[\s\S]*<\/svg>/)?.[0] ?? null);
    } catch {
      svgCache.set(code, null);
    }
  }
  return svgCache.get(code);
}

const titleCase = (value) =>
  value.replace(/\b\w/g, (char) => char.toUpperCase());

/** code → { name, flag, countries[] } */
const byCode = new Map();
for (const country of countries) {
  const code2 = country.cca2;
  if (!code2 || !country.currencies) continue;
  const name = country.name?.common ?? code2;
  for (const [currencyCode, meta] of Object.entries(country.currencies)) {
    const entry = byCode.get(currencyCode) ?? {
      code: currencyCode,
      name: "",
      flag: "",
      countries: [],
    };
    entry.countries.push(name);
    if (!entry.name && typeof meta?.name === "string" && meta.name) {
      entry.name = titleCase(meta.name);
    }
    if (!entry.flag && FLAG_OVERRIDES[currencyCode]) {
      entry.flag = FLAG_OVERRIDES[currencyCode];
    }
    byCode.set(currencyCode, entry);
  }
}

const entries = [];
const missingFlags = [];
for (const entry of byCode.values()) {
  entry.countries.sort();
  entry.name ||= entry.code;
  if (!entry.flag) {
    entry.flag =
      entry.countries
        .map((name) => countries.find((c) => c.name?.common === name)?.cca2)
        .find((code2) => code2 && availableFlags.has(code2)) ?? "";
  }
  if (!entry.flag || !availableFlags.has(entry.flag)) {
    missingFlags.push(`${entry.code} (tried ${entry.flag || "none"})`);
    entry.flag = "";
  }
  entries.push(entry);
}
entries.sort((a, b) => a.code.localeCompare(b.code));

/* ---- write src/lib/currency-data.ts ---- */
const dataLines = entries.map(({ code, name, flag, countries }) => {
  const countriesJson = JSON.stringify(countries);
  return `  { code: "${code}", name: "${name}", flag: "${flag}", countries: ${countriesJson} },`;
});
const data = `/**
 * Generated by scripts/generate-currency-data.mjs — do not edit by hand.
 * Every currency used by any country (ISO 4217), with a representative SVG
 * flag code (ISO 3166-1 alpha-2, "EU" for the euro) and the countries that
 * use it (for search). Flags live in public/flags/<CODE>.svg.
 */
export interface CurrencyEntry {
  /** ISO 4217 code, e.g. "USD". */
  code: string;
  /** Display name, e.g. "US Dollar". */
  name: string;
  /** Representative flag code: ISO 3166-1 alpha-2 (or "EU"). */
  flag: string;
  /** Countries that use this currency (search terms). */
  countries: string[];
}

export const CURRENCIES: CurrencyEntry[] = [
${dataLines.join("\n")}
];
`;
writeFileSync(join(process.cwd(), "src/lib/currency-data.ts"), data);

/* ---- write public/flags/*.svg ---- */
const flagsOut = join(process.cwd(), "public/flags");
mkdirSync(flagsOut, { recursive: true });
let written = 0;
for (const entry of entries) {
  if (!entry.flag) continue;
  const svg = getSvg(entry.flag);
  if (svg) {
    writeFileSync(join(flagsOut, `${entry.flag}.svg`), svg);
    written += 1;
  }
}

console.log(`✓ ${entries.length} currencies → src/lib/currency-data.ts`);
console.log(`✓ ${written} flags → public/flags/`);
if (missingFlags.length) {
  console.warn(`⚠ no flag for: ${missingFlags.join(", ")}`);
}
